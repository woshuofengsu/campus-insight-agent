def detect_intent(text: str, role: str = "resident") -> str | None:
    """返回第一个匹配意图（多意图先处理第一个主要意图）。"""
    table = GRID_INTENTS if role == "grid" else (ELDERLY_INTENTS if role == "elderly" else RESIDENT_INTENTS)
    for intent, kws, _desc in table:
        if any(kw in text for kw in kws):
            return intent
    return None


def intent_desc(intent: str, role: str = "resident") -> str:
    table = GRID_INTENTS if role == "grid" else (ELDERLY_INTENTS if role == "elderly" else RESIDENT_INTENTS)
    for i, _kws, desc in table:
        if i == intent:
            return desc
    return ""


def detect_emergency(text: str) -> bool:
    return any(w in text for w in EMERGENCY_WORDS)


def detect_emotion(text: str) -> bool:
    return any(w in text for w in EMOTION_WORDS)


def detect_polite(text: str) -> bool:
    return any(w in text for w in POLITE_WORDS)


def detect_go_out(text: str) -> bool:
    return any(w in text for w in GO_OUT_WORDS)


