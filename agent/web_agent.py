def correct_text(text: str) -> str:
    """规则级错别字/病句纠正；返回纠正后文本（未变则原样）。"""
    t = (text or "").strip()
    t = re.sub(r"\s+", " ", t)
    t = re.sub(r"([。！？!?，,\.])\1+", r"\1", t)
    for pat, rep in _CORRECTIONS:
        t = re.sub(pat, rep, t)
    return t


